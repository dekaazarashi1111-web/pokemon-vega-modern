def root_registration(raw, root):
    need(any(exact(root, r) for r in ROOTS), '選択2登録根のみ')
    chain = root['root_chain']; d.signed(raw, chain)
    groups, group, maprow, header, events, obj = chain
    for row in (groups, group, maprow):
        need(row['size'] == 4 and d.u32(raw, row['address']) == row['value'], '現root pointer値')
    need(groups['address'] == 0x08054B0C and group['address'] == groups['value'] + root['group'] * 4 and maprow['address'] == group['value'] + root['map'] * 4 and header['address'] == maprow['value'], '現map登録連鎖')
    need(header['size'] == 8 and d.u32(raw, header['address'] + 4) == events['address'] and events['size'] == 8 and d.u32(raw, events['address'] + 4) == events['objects'], '現events pointer連鎖')
    need(chunk(raw, events['address'], 1)[0] > root['object'] and obj['size'] == 24 and obj['address'] == events['objects'] + root['object'] * 24 and obj['script_field'] == obj['address'] + 16 and d.u32(raw, obj['script_field']) == root['script'], '24byte現object/script field')
    return dict(owner_id=root['owner_id'], script=root['script'], registration_bound=True)


def command_size(opcode):
    need(type(opcode) is int and opcode in GRAMMAR, '既知grammarのみ。未対応を不達扱いしない')
    return 1 + sum({'B': 1, 'H': 2, 'W': 4}[c] for c in GRAMMAR[opcode]['operands'])


def trace_graph(raw, root, expand_standards=True):
    need(type(expand_standards) is bool, '明示的なgraph種別')
    root_registration(raw, root)
    queue = deque([(root['script'], ())]); seen = set(); rows = []
    while queue:
        pc, stack = queue.popleft()
        if (pc, stack) in seen:
            continue
        need(len(seen) < 512 and len(stack) <= 8, '有限graph上限、未完を終端へ変換しない')
        seen.add((pc, stack)); opcode = chunk(raw, pc, 1)[0]; size = command_size(opcode)
        value = chunk(raw, pc, size); command = GRAMMAR[opcode]['name']
        if opcode == 2:
            targets = []
        elif opcode == 3:
            need(stack, '登録根の未対応空returnは不達へ変換しない')
            targets = [(stack[-1], stack[:-1])]
        elif opcode == 4:
            targets = [(d.u32(raw, pc + 1), stack + (pc + size,))]
        elif opcode == 5:
            targets = [(d.u32(raw, pc + 1), stack)]
        elif opcode == 6:
            need(value[1] < 6, '既知比較条件のみ')
            targets = [(pc + size, stack), (d.u32(raw, pc + 2), stack)]
        elif opcode == 9 and expand_standards:
            index = value[1]; need(index in (4, 5), 'scope標準4/5のみ')
            targets = [(d.u32(raw, 0x08163758 + index * 4), stack + (pc + size,))]
        else:
            targets = [(pc + size, stack)]
        rows.append(dict(address=pc, size=size, sha256=hashlib.sha256(value).hexdigest(), opcode=opcode,
                         command=command, stack=list(stack), successors=[dict(address=a, stack=list(s)) for a, s in targets]))
        queue.extend(targets)
    return dict(owner_id=root['owner_id'], root=root['script'], standard_edges_expanded=expand_standards,
                state_count=len(rows), nodes=rows,
                target_loadwords_found=sorted({r['address'] for r in rows} & set(TARGET_LOADWORDS)),
                unhandled_opcodes=[], bounded_graph_complete=True,
                runtime_effects_proven=False, all_roots_unreachable_claimed=False)


def bind_semantics(raw):
    d.signed(raw, FIXED_WINDOWS)
    for ins in INS.values():
        need(chunk(raw, ins.address, ins.size) == encoded(ins), '独立Thumb encoderと現command/helper一致 ' + hex(ins.address))
    for address, value in LITERALS.items():
        need(d.u32(raw, address) == value, '現literal/dispatch/hook/placeholder slot')
    for row in NEW_HANDLERS:
        need(d.u32(raw, 0x08162CC4 + 4 * row['opcode']) == row['address'] | 1, '現JP handler dispatch')
        expected = command_size(row['opcode']) - 1
        need(expected == row['operand_bytes'], '新command operand extent')
    # source grammarと実prefix境界を独立して検査。hook以降の副作用は仮定しない。
    need(INS[0x08069E14].args == (0x080691B8,) and INS[0x08069E24].args == (0x080691B8,) and
         INS[0x08069E1C].args == (0x0806DC48,) and INS[0x08069E2C].args == (0x0806DC48,) and
         INS[0x08069E3A].args == (False, 'byte', 0, 4, 2), '比較の2halfword reader/2現hook呼出し/比較結果store')
    need(INS[0x0806A134].args == (True, 'byte', 2, 1, 0) and
         INS[0x0806A138].args == (False, 'word', 1, 0, 8) and
         INS[0x0806A13C].args == (0x08054750,), '統計commandの実byte reader/次PC store/opaque callee')
    need(d.u32(raw, 0x0806DC4C) == 0x090970DD, 'GetVarPointerの現hook、stock実行に偽装しない')
    for root in ROOTS:
        root_registration(raw, root)
    for text in TEXTS:
        call = text['loadword_and_callstd']; b = chunk(raw, call['address'], 8)
        need(b[0] == 15 and b[1] == 0 and int.from_bytes(b[2:6], 'little') == text['address'] and b[6:] == bytes((9, 4)), '対象局所LOADWORD0/CALLSTD4')
        b = chunk(raw, text['address'], text['size'])
        need(b[-1] == 255 and 255 not in b[:-1], '対象局所EOS、消費の証拠へ昇格しない')
    need(chunk(raw, 0x0818DD2C, 2) == bytes((253, 3)), '対象FD03')


class Machine(rt.Machine):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs); self.reads = []; self.visited = []
    def read(self, address, size):
        self.reads.append((address, size)); return super().read(address, size)
    def step(self, *args, **kwargs):
        self.visited.append(self.pc); return super().step(*args, **kwargs)


