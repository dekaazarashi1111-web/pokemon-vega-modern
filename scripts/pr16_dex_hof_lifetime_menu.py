def encoded(ins):
    k,x=ins.kind,ins.args
    if k=='spaddr': n=0xA800|(x[0]<<8)|(x[1]//4)
    elif k=='comparehi':rd,rs=x;n=0x4500|((rd&8)<<4)|(rs<<3)|(rd&7)
    elif k=='addhi':rd,rs=x;n=0x4400|((rd&8)<<4)|(rs<<3)|(rd&7)
    elif k in ('sub','subi'):rd,rs,rt=x;n=(0x1A00 if k=='sub' else 0x1E00)|(rt<<6)|(rs<<3)|rd
    elif k=='alu_ext':
        op,rd,rs=x;n=0x4000|({'and':0,'eor':1,'lsl':2,'lsr':3,'asr':4,'adc':5,'sbc':6,'ror':7,'tst':8,'neg':9,'cmn':11,'orr':12,'mul':13,'bic':14,'mvn':15}[op]<<6)|(rs<<3)|rd
    elif k=='regmem':
        op,rd,rb,ro=x;n=0x5000|({'str':0,'strh':1,'strb':2,'ldrsb':3,'ldr':4,'ldrh':5,'ldrb':6,'ldrsh':7}[op]<<9)|(ro<<6)|(rb<<3)|rd
    else:return shared.encoded(ins)
    return n.to_bytes(2,'little')

def cursor_transition(cursor,minimum,maximum,delta,wrap=False):
    """機械制約に対応する条件付き算術モデル。RAM非干渉を証明する関数ではない。"""
    need(type(cursor) is int and type(minimum) is int and type(maximum) is int,'integer cursor contract')
    need(0<=minimum<=cursor<=maximum<128 and delta in (-1,0,1),'cursor precondition')
    target=cursor+delta
    if target<minimum:return maximum if wrap else minimum
    if target>maximum:return minimum if wrap else maximum
    return target

